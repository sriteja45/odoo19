    def _fetch_sure_seal_products(self, keyword=None, category=None, records=100):
        api_model = request.env['mouser.manufacturer'].sudo()
        search_keyword = (keyword or '').strip() or 'Sure-Seal'
        if search_keyword.lower() != 'sure-seal' and 'sure-seal' not in search_keyword.lower():
            search_keyword = 'Sure-Seal ' + search_keyword
        if category:
            search_keyword = search_keyword + ' ' + category
        api_data = api_model._mouser_search_keyword_raw(search_keyword, records=records, starting_record=0)
        search_results = api_data.get('SearchResults') or {}
        parts = search_results.get('Parts') or []
        products = [self._normalise_mouser_product(part) for part in parts]
        total_results = search_results.get('NumberOfResult') or search_results.get('TotalResults') or len(products)
        return products, total_results

    def _apply_sure_seal_filters(self, products, kwargs):
        filtered = list(products)
        if kwargs.get('instock'):
            filtered = [p for p in filtered if p.get('availability') and '0' not in p.get('availability', '').split()[0:1]]
        if kwargs.get('active'):
            filtered = [p for p in filtered if not p.get('lifecycle') or 'obsolete' not in p.get('lifecycle', '').lower()]
        if kwargs.get('rohs'):
            filtered = [p for p in filtered if 'rohs' in (p.get('rohs') or '').lower() or 'compliant' in (p.get('rohs') or '').lower()]
        return filtered

