import requests

class MouserProductSearchController(http.Controller):

    @http.route(['/product/search'], type='http', auth='public', website=True, sitemap=False)
    def product_search(self, keyword=None, **kwargs):
        keyword = keyword or request.params.get('keyword') or 'resistor'

        api_key = request.env['ir.config_parameter'].sudo().get_param(
            'mouser_theme.mouser_api_key'
        )

        products = []
        error = False

        if api_key:
            try:
                url = f"https://api.mouser.com/api/v2/search/keyword?apiKey={api_key}"

                payload = {
                    "SearchByKeywordRequest": {
                        "keyword": keyword,
                        "records": 10,
                        "startingRecord": 0,
                        "searchOptions": "string"
                    }
                }

                headers = {"Content-Type": "application/json"}

                response = requests.post(url, json=payload, headers=headers, timeout=20)
                response.raise_for_status()

                data = response.json()

                parts = data.get('SearchResults', {}).get('Parts', [])

                for part in parts:
                    products.append({
                        'manufacturer': part.get('Manufacturer', ''),
                        'mpn': part.get('ManufacturerPartNumber', ''),
                        'mouser_no': part.get('MouserPartNumber', ''),
                        'description': part.get('Description', ''),
                        'availability': part.get('Availability', ''),
                        'datasheet': part.get('DataSheetUrl', ''),
                        'image': part.get('ImagePath', ''),
                        'detail_url': part.get('ProductDetailUrl', ''),
                    })

            except Exception as e:
                error = str(e)
        else:
            error = 'Mouser API key not configured.'

        values = {
            'keyword': keyword,
            'products': products,
            'error': error,
        }

        return request.render('mouser_theme.product_search_results_template', values)


import requests

class MouserProductController(http.Controller):

    @http.route('/product/detail', type='http', auth='public', website=True)
    def product_detail(self, mouser_no=None, **kwargs):
        product = {}
        if mouser_no:
            api_key = request.env['ir.config_parameter'].sudo().get_param('mouser_theme.mouser_api_key')
            headers = {'Content-Type': 'application/json'}
            payload = {
                "SearchByPartRequest": {
                    "mouserPartNumber": mouser_no,
                    "partSearchOptions": ""
                }
            }
            try:
                response = requests.post(
                    f"https://api.mouser.com/api/v2/search/partnumber?apiKey={api_key}",
                    json=payload,
                    headers=headers,
                    timeout=20
                )
                data = response.json()
                parts = data.get('SearchResults', {}).get('Parts', [])
                if parts:
                    product = parts[0]
            except Exception as e:
                product = {'error': str(e)}
        return request.render('mouser_theme.product_detail_template', {'product': product})
