    def _normalise_mouser_product(self, part):
        prices = []
        for pb in (part.get('PriceBreaks') or [])[:5]:
            qty = pb.get('Quantity') or pb.get('quantity') or ''
            price = pb.get('Price') or pb.get('price') or ''
            if qty or price:
                prices.append({'qty': qty, 'price': price})
        return {
            'manufacturer': part.get('Manufacturer') or 'Sure-Seal',
            'mpn': part.get('ManufacturerPartNumber') or '',
            'mouser_no': part.get('MouserPartNumber') or '',
            'description': part.get('Description') or '',
            'availability': part.get('Availability') or '',
            'datasheet': part.get('DataSheetUrl') or '',
            'image': part.get('ImagePath') or '',
            'detail_url': part.get('ProductDetailUrl') or '#',
            'category': part.get('Category') or '',
            'lifecycle': part.get('LifecycleStatus') or part.get('LifeCycleStatus') or '',
            'rohs': part.get('ROHSStatus') or part.get('RoHSStatus') or part.get('ROHS') or '',
            'prices': prices,
        }

